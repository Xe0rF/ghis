    fn replacement_is_idempotent() {
        let block = managed_block(Path::new("/tmp/a path/init.zsh"));
        let once = replace_managed_block("export A=1\n", &block);
        let twice = replace_managed_block(&once, &block);
        assert_eq!(once, twice);
        assert_eq!(once.matches(START_MARKER).count(), 1);
    }

    #[test]
    fn malformed_block_is_not_removed() {
        let input = format!("before\n{START_MARKER}\ntruncated\n");
        let (output, changed) = remove_managed_blocks(&input);
        assert!(!changed);
        assert_eq!(output, input);
    }

    #[test]
    fn replacement_preserves_content_after_an_unmatched_start() {
        let malformed = format!("before\n{START_MARKER}\nuser content\n");
        let block = managed_block(Path::new("/tmp/init.zsh"));
        let once = replace_managed_block(&malformed, &block);
        let twice = replace_managed_block(&once, &block);

        assert_eq!(twice, once);
        assert!(twice.contains("user content"));
        assert_eq!(twice.matches(START_MARKER).count(), 2);
    }

    #[test]
    fn removal_preserves_nested_malformed_block_and_orphan_end() {
        let input = format!(
            "before\n{END_MARKER}\n{START_MARKER}\nmalformed\n{START_MARKER}\nmanaged\n{END_MARKER}\nafter\n"
        );
        let (output, changed) = remove_managed_blocks(&input);

        assert!(changed);
        assert_eq!(
            output,
            format!("before\n{END_MARKER}\n{START_MARKER}\nmalformed\nafter\n")
        );
    }

    #[test]
    fn setup_and_uninstall_round_trip() {
        let directory = tempfile::tempdir().expect("tempdir");
        let zshrc = directory.path().join(".zshrc");
        let init = directory.path().join("config/init.zsh");
        fs::write(&zshrc, "export TEST=1\n").expect("write");
        let report = setup(&zshrc, &init, "ghis").expect("setup");
        assert!(report.changed);
        assert!(report.backup.is_some());
        assert!(integration_is_installed(&zshrc, &init, "ghis"));
        assert!(
            fs::read_to_string(&zshrc)
                .expect("read")
                .contains(START_MARKER)
        );
        let second = setup(&zshrc, &init, "ghis").expect("second setup");
        assert!(!second.changed);
        assert!(uninstall(&zshrc).expect("uninstall"));
        let after_uninstall = fs::read_to_string(&zshrc).expect("read");
        assert!(!after_uninstall.contains(START_MARKER));
        assert!(!integration_is_installed(&zshrc, &init, "ghis"));
        assert_eq!(after_uninstall, "export TEST=1\n");
        assert!(!uninstall(&zshrc).expect("second uninstall"));
        assert_eq!(fs::read_to_string(&zshrc).expect("read"), after_uninstall);
    }

    #[cfg(unix)]
